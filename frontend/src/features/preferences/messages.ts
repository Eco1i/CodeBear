export function translate(
  language: AppLanguage,
  key: string,
  params: MessageParams = {},
): string {
  const template = messages[language][key] || messages["zh-CN"][key] || key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : `{${name}}`,
  );
}

export function translateError(
  language: AppLanguage,
  error: unknown,
  fallbackKey = "error.generic",
): string {
  const candidate =
    error && typeof error === "object"
      ? (error as { code?: unknown; message?: unknown })
      : {};
  const code = typeof candidate.code === "string" ? candidate.code : "";
  const localizedApiError = code
    ? API_ERROR_MESSAGES[code]?.[language]
    : undefined;
  if (localizedApiError) return localizedApiError;
  const translated = code ? messages[language][`error.${code}`] : undefined;
  if (translated) return translate(language, `error.${code}`);
  let message = "";
  if (error instanceof Error) {
    message = error.message;
  } else if (typeof candidate.message === "string") {
    message = candidate.message;
  }
  if (message && (language === "zh-CN" || !/[\u4e00-\u9fff]/.test(message)))
    return message;
  return translate(language, fallbackKey);
}
